interface PluginSettingsContextValue {
  theme: PluginTheme;
  setTheme: (theme: PluginTheme) => void;
  toggleTheme: () => void;
  isDark: boolean;
  locale: PluginLocale;
  setLocale: (locale: PluginLocale) => void;
  t: (key: string) => string;
}

const PluginSettingsContext = createContext<PluginSettingsContextValue | null>(null);

export function PluginProvider({ children }: { children: ReactNode }) {
  const [theme, _setTheme] = useState<PluginTheme>(() =>
    (localStorage.getItem(THEME_KEY) as PluginTheme) || 'dark',
  );
  const [locale, _setLocale] = useState<PluginLocale>(() =>
    (localStorage.getItem(LOCALE_KEY) as PluginLocale) || 'es',
  );

  const setTheme = useCallback((t: PluginTheme) => {
    _setTheme(t);
    localStorage.setItem(THEME_KEY, t);
  }, []);

  const toggleTheme = useCallback(() => {
    _setTheme((prev) => {
      const next = prev === 'dark' ? 'light' : 'dark';
      localStorage.setItem(THEME_KEY, next);
      return next;
    });
  }, []);

  const setLocale = useCallback((l: PluginLocale) => {
    _setLocale(l);
    localStorage.setItem(LOCALE_KEY, l);
  }, []);

  const t = useCallback(
    (key: string) => dict[locale]?.[key] ?? dict.es[key] ?? key,
    [locale],
  );

  return (
    <PluginSettingsContext.Provider
      value={{ theme, setTheme, toggleTheme, isDark: theme === 'dark', locale, setLocale, t }}
    >
      {children}
    </PluginSettingsContext.Provider>
  );
}

export function usePluginSettings() {
  const ctx = useContext(PluginSettingsContext);
  if (!ctx) throw new Error('usePluginSettings must be used within PluginProvider');
  return ctx;
}

